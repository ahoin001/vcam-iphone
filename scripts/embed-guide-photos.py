#!/usr/bin/env python3
"""Regenerate windows/src/guide_photos.h from the guide photos the iPhone app bundles.

ios/VCamdroid/Guide/guide-<name>.jpg is the single copy of each photo. The phone serves
them at /guide/<name>.jpg; VCamPanel embeds them so its Guide works before a phone connects.
Run this after adding, replacing, or removing a photo there.
"""

import base64
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "ios" / "VCamdroid" / "Guide"
OUTPUT = ROOT / "windows" / "src" / "guide_photos.h"
CHUNK = 12000  # MSVC rejects a single string literal past 16 KB.


def identifier(name: str) -> str:
    return "k" + "".join(part.capitalize() for part in name.split("-"))


def main() -> None:
    photos = sorted(SOURCE.glob("guide-*.jpg"))
    lines = [
        "#pragma once",
        "",
        "// Generated by scripts/embed-guide-photos.py from ios/VCamdroid/Guide. Do not edit by hand.",
        "",
        "namespace guide_photos {",
        "",
        "struct Photo {",
        "    const char* name;",
        "    const char* const* chunks;",
        "    int count;",
        "};",
        "",
    ]
    entries = []
    for path in photos:
        name = path.stem.removeprefix("guide-")
        encoded = base64.b64encode(path.read_bytes()).decode("ascii")
        chunks = [encoded[i:i + CHUNK] for i in range(0, len(encoded), CHUNK)]
        lines.append(f"inline constexpr const char* {identifier(name)}[] = {{")
        lines.extend(f'    "{chunk}",' for chunk in chunks)
        lines.append("};")
        lines.append("")
        entries.append(f'    {{"{name}", {identifier(name)}, {len(chunks)}}},')
    lines.append("inline constexpr Photo kPhotos[] = {")
    lines.extend(entries)
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace guide_photos")
    lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="ascii")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} with {len(photos)} photos")


if __name__ == "__main__":
    main()
